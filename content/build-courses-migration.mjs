// Generates supabase/migrations/0021_courses_seed.sql from the Markdown
// lessons in content/courses/<subject>/<course dir>/NN-name.md.
//
//   node content/build-courses-migration.mjs
//
// Each lesson file starts with a frontmatter block:
//   ---
//   title: Sets
//   minutes: 25
//   ---
// The migration is idempotent: courses upsert on slug, lessons upsert on
// (course_id, position), so re-running it after editing a lesson updates
// the text without duplicating anything or touching student progress.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const catalog = JSON.parse(readFileSync(join(root, "courses/catalog.json"), "utf8"));
const REQUIRED_TIER = "premium_plus"; // same default as the courses table

const sqlText = (s) => `'${s.replaceAll("'", "''")}'`;
function dollar(body) {
  let tag = "md";
  while (body.includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${body}$${tag}$`;
}

const out = [];
out.push(`-- GENERATED by content/build-courses-migration.mjs — edit the Markdown files in
-- content/courses/ and re-run the script instead of editing this file.
--
-- Seeds the Mathématiques / Physique / Chimie course catalogue: one course
-- per module, one 'notes' lesson per Markdown file (rendered with Markdown
-- + KaTeX by components/math-content.tsx). Idempotent: courses upsert on
-- slug and lessons on (course_id, position), so re-applying it refreshes
-- the text and leaves lesson_progress untouched.
--
-- Hand-made courses are removed once by 0021_remove_hand_made_courses.sql, which
-- runs before this file. This seed itself never deletes anything, and a course
-- created by hand later (created_by is set) is left untouched if it reuses a slug.
`);

// Fail loudly (instead of silently inserting nothing) if the three subjects
// from 0013_exam_subjects_seed.sql are missing: the course inserts below look
// the subject up by slug and would otherwise match zero rows.
out.push(`do $$
begin
${catalog.subjects
  .map(
    (s) => `  if not exists (select 1 from public.subjects where slug in (${s.subjectSlugs.map(sqlText).join(", ")})) then
    raise exception 'subject ${s.slug} not found (looked for slugs: ${s.subjectSlugs.join(", ")}): create it or add its slug to content/courses/catalog.json';
  end if;`,
  )
  .join("\n")}
end
$$;
`);

let subjectOrder = 0;
let courseCount = 0;
const perCourse = [];
let lessonCount = 0;
for (const subject of catalog.subjects) {
  subjectOrder += 1;
  let courseOrder = 0;
  for (const course of subject.courses) {
    courseOrder += 1;
    const dir = join(root, "courses", subject.slug, course.dir);
    const files = existsSync(dir) ? readdirSync(dir).filter((f) => /^\d+-.*\.md$/.test(f)).sort() : [];
    if (files.length === 0) {
      console.warn(`skip ${course.slug}: no lessons in ${dir}`);
      continue;
    }
    courseCount += 1;
    perCourse.push([course.slug, files.length]);
    out.push(`-- ${course.title}`);
    out.push(`insert into public.courses (subject_id, title, slug, description, required_plan_tier, is_published, display_order)
select s.id, ${sqlText(course.title)}, ${sqlText(course.slug)}, ${sqlText(course.description)}, '${REQUIRED_TIER}', true, ${subjectOrder * 10 + courseOrder}
from public.subjects s where s.slug in (${subject.subjectSlugs.map(sqlText).join(", ")}) order by s.display_order limit 1
on conflict (slug) do update set
  subject_id = excluded.subject_id,
  title = excluded.title,
  description = excluded.description,
  display_order = excluded.display_order,
  is_published = true
where public.courses.created_by is null;
`);
    for (const file of files) {
      const raw = readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n");
      const m = raw.match(/^---\n([\s\S]*?)\n---\n/);
      if (!m) throw new Error(`${file}: missing frontmatter`);
      const meta = Object.fromEntries(m[1].split("\n").map((l) => [l.slice(0, l.indexOf(":")).trim(), l.slice(l.indexOf(":") + 1).trim().replace(/^"(.*)"$/, "$1")]));
      if (!meta.title) throw new Error(`${file}: frontmatter needs a title`);
      const body = raw.slice(m[0].length).trim();
      const position = parseInt(file, 10);
      const seconds = (parseInt(meta.minutes ?? "20", 10) || 20) * 60;
      lessonCount += 1;
      out.push(`insert into public.lessons (course_id, title, position, content_type, notes_body, duration_seconds, is_published)
select c.id, ${sqlText(meta.title)}, ${position}, 'notes', ${dollar(body)}, ${seconds}, true
from public.courses c where c.slug = ${sqlText(course.slug)} and c.created_by is null
on conflict (course_id, position) do update set
  title = excluded.title,
  content_type = 'notes',
  notes_body = excluded.notes_body,
  duration_seconds = excluded.duration_seconds,
  is_published = true;
`);
    }
  }
}
const expected = perCourse.map(([slug, n]) => `('${slug}', ${n})`).join(", ");
out.push(`-- Post-condition: every seed course that is not shadowed by a hand-made course
-- must exist with all of its lessons.
do $$
declare
  r record;
  n integer;
begin
  for r in select * from (values ${expected}) as v (slug, expected_lessons) loop
    if exists (select 1 from public.courses where slug = r.slug and created_by is not null) then
      raise notice 'course % already exists (created by hand): left untouched, seed course skipped', r.slug;
      continue;
    end if;
    select count(*) into n from public.lessons l join public.courses c on c.id = l.course_id where c.slug = r.slug;
    if n < r.expected_lessons then
      raise exception 'course seed incomplete for %: % lessons, expected %', r.slug, n, r.expected_lessons;
    end if;
  end loop;
end
$$;
`);
writeFileSync(join(root, "../supabase/migrations/0022_courses_seed.sql"), out.join("\n"));

// One-time clean-up, applied BEFORE the seed (hence the lower number): the owner
// asked to keep ONLY the courses generated from content/courses/. Deleting a course
// cascades to its lessons and to lesson_progress (students' progress in them).
// It is a separate migration so that re-applying the seed later never deletes
// courses created afterwards.
const seedSlugs = catalog.subjects.flatMap((s) => s.courses.map((c) => `'${c.slug}'`)).join(", ");
writeFileSync(
  join(root, "../supabase/migrations/0021_remove_hand_made_courses.sql"),
  `-- GENERATED by content/build-courses-migration.mjs.
--
-- ONE-TIME, DESTRUCTIVE: keeps only the ${courseCount} courses seeded by
-- 0022_courses_seed.sql and deletes every other course, including the ones created
-- by hand in the admin (created_by is set) -- also a hand-made course that happens
-- to use one of the seed slugs, so that 0022 can recreate it from the Markdown.
-- Deleting a course cascades to its lessons and to lesson_progress, so students'
-- progress in the deleted courses is lost for good. Back the database up first.
do $$
declare
  n integer;
begin
  delete from public.courses
  where created_by is not null
     or slug not in (${seedSlugs});
  get diagnostics n = row_count;
  raise notice 'removed % course(s) that are not part of the seed', n;
end
$$;
`,
);
console.log(`wrote 0021_remove_hand_made_courses.sql and 0022_courses_seed.sql: ${courseCount} courses, ${lessonCount} lessons`);
